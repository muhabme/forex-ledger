// Regenerates src/money/currencies.generated.ts: every fiat currency Frankfurter
// has rates for, with its decimals from the official ISO 4217 list.
// Run with `npm run currencies:update` and commit the result.
import { writeFile } from "node:fs/promises";

const FRANKFURTER_CURRENCIES_URL = "https://api.frankfurter.dev/v2/currencies";
// Published by SIX Group, the ISO 4217 maintenance agency.
const ISO_4217_URL =
  "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";
const OUTPUT_FILE = new URL(
  "../src/money/currencies.generated.ts",
  import.meta.url,
);

export interface FrankfurterCurrency {
  iso_code: string;
  name: string;
  type: string;
}

export interface CurrencyEntry {
  code: string;
  name: string;
  decimals: number;
}

export interface IsoList {
  published: string;
  minorUnits: Map<string, number>;
}

export function parseIsoList(xml: string): IsoList {
  const published = /Pblshd="([\d-]+)"/.exec(xml)?.[1];

  if (published === undefined) {
    throw new Error("ISO 4217 list has no publication date");
  }

  const minorUnits = new Map<string, number>();

  for (const [, entry = ""] of xml.matchAll(
    /<CcyNtry>([\s\S]*?)<\/CcyNtry>/g,
  )) {
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(entry)?.[1];
    // Entries such as gold or SDR have "N.A."" instead of a number and are skipped.
    const digits = /<CcyMnrUnts>(\d+)<\/CcyMnrUnts>/.exec(entry)?.[1];

    if (code !== undefined && digits !== undefined) {
      minorUnits.set(code, Number(digits));
    }
  }

  return { published, minorUnits };
}

export function buildCurrencyTable(
  frankfurterCurrencies: FrankfurterCurrency[],
  minorUnits: Map<string, number>,
): { currencies: CurrencyEntry[]; skipped: string[] } {
  const currencies: CurrencyEntry[] = [];
  const skipped: string[] = [];

  for (const { iso_code: code, name, type } of frankfurterCurrencies) {
    if (type !== "currency") {
      continue;
    }

    const decimals = minorUnits.get(code);

    // not an iso 4217 currency so it has no official decimals.
    if (decimals === undefined) {
      skipped.push(code);
      continue;
    }

    currencies.push({ code, name, decimals });
  }

  currencies.sort((a, b) => a.code.localeCompare(b.code));

  return { currencies, skipped: skipped.sort() };
}

export function renderModule(
  currencies: CurrencyEntry[],
  isoPublished: string,
): string {
  const rows = currencies.map(
    ({ code, name, decimals }) =>
      `  { code: ${JSON.stringify(code)}, name: ${JSON.stringify(name)}, decimals: ${String(decimals)} },`,
  );

  return [
    "// Generated by scripts/update-currencies.ts. Do not edit by hand;",
    "// run `npm run currencies:update` instead.",
    `// Sources: Frankfurter v2 currency list, ISO 4217 list published ${isoPublished}.`,
    'import type { Currency } from "./currency.js";',
    "",
    "export const CURRENCIES: readonly Currency[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

async function download(url: string): Promise<Response> {
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`${url} responded ${String(response.status)}`);
  }

  return response;
}

async function main(): Promise<void> {
  const [frankfurterResponse, isoResponse] = await Promise.all([
    download(FRANKFURTER_CURRENCIES_URL),
    download(ISO_4217_URL),
  ]);

  const frankfurterCurrencies =
    (await frankfurterResponse.json()) as FrankfurterCurrency[];

  const iso = parseIsoList(await isoResponse.text());
  const { currencies, skipped } = buildCurrencyTable(
    frankfurterCurrencies,
    iso.minorUnits,
  );

  await writeFile(OUTPUT_FILE, renderModule(currencies, iso.published));
  console.info(
    `Wrote ${String(currencies.length)} currencies. Skipped (not in ISO 4217): ${skipped.join(", ")}`,
  );
}

// Only run when executed directly, not when the tests import this file.
if (import.meta.main) {
  await main();
}
